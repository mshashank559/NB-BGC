import ExcelJS from 'exceljs';
import { PDFDocument, rgb, StandardFonts } from 'pdf-lib';
import { CandidateRecord, AuditEntry } from '../types';

export interface MonthlyReportData {
  month: string;
  year: number;
  candidates: CandidateRecord[];
  auditEntries: AuditEntry[];
}

/**
 * Generates an Excel monthly report buffer using ExcelJS.
 */
export async function generateMonthlyExcelReport(data: MonthlyReportData): Promise<Uint8Array> {
  const workbook = new ExcelJS.Workbook();
  workbook.creator = 'Candidate Compliance & Payments Engine';
  workbook.created = new Date();

  // Sheet 1: Executive Summary & Collections
  const summarySheet = workbook.addWorksheet('Collections & Summary');
  summarySheet.columns = [
    { header: 'Candidate Name', key: 'candidateName', width: 25 },
    { header: 'Sales Person', key: 'salesPerson', width: 20 },
    { header: 'Team Lead', key: 'teamLead', width: 20 },
    { header: 'End Client', key: 'endClient', width: 25 },
    { header: 'PO Month', key: 'poMonth', width: 16 },
    { header: 'Total Payable ($)', key: 'totalPayable', width: 18 },
    { header: 'Total Paid ($)', key: 'totalPaid', width: 16 },
    { header: 'Balance ($)', key: 'balance', width: 16 },
    { header: 'BGC Status', key: 'bgcStatus', width: 16 },
    { header: 'Status', key: 'status', width: 14 },
  ];

  data.candidates.forEach((cand) => {
    const installments = cand.paymentPlan?.installments || [];
    const totalPaid = installments
      .filter((i) => i.status === 'PAID')
      .reduce((sum, i) => sum + i.amount, 0);
    const totalPayable = cand.paymentPlan?.totalPayable || cand.upfrontAmount;
    const balance = Math.max(0, totalPayable - totalPaid);

    summarySheet.addRow({
      candidateName: cand.candidateName,
      salesPerson: cand.salesPerson,
      teamLead: cand.teamLead,
      endClient: cand.endClient,
      poMonth: cand.poMonth,
      totalPayable,
      totalPaid,
      balance,
      bgcStatus: cand.bgcOfferStatus,
      status: cand.status,
    });
  });

  // Sheet 2: Installment Collections Ledger
  const instSheet = workbook.addWorksheet('Installment Slots');
  instSheet.columns = [
    { header: 'Candidate Name', key: 'candidateName', width: 25 },
    { header: 'Slot #', key: 'slot', width: 10 },
    { header: 'Tier', key: 'tier', width: 15 },
    { header: 'Amount ($)', key: 'amount', width: 14 },
    { header: 'Due Date', key: 'dueDate', width: 16 },
    { header: 'Paid Date', key: 'paidDate', width: 16 },
    { header: 'Slot Status', key: 'status', width: 16 },
    { header: 'Invoice #', key: 'invoiceNumber', width: 18 },
    { header: 'Invoice Status', key: 'invoiceStatus', width: 16 },
  ];

  data.candidates.forEach((cand) => {
    (cand.paymentPlan?.installments || []).forEach((inst) => {
      instSheet.addRow({
        candidateName: cand.candidateName,
        slot: inst.number,
        tier: inst.tier,
        amount: inst.amount,
        dueDate: inst.dueDate,
        paidDate: inst.paidDate || 'N/A',
        status: inst.status,
        invoiceNumber: inst.invoiceNumber || 'Pending',
        invoiceStatus: inst.invoiceStatus || 'Draft',
      });
    });
  });

  // Sheet 3: Audit Changes & Remarks
  const auditSheet = workbook.addWorksheet('Audit Log & Remarks');
  auditSheet.columns = [
    { header: 'Candidate', key: 'candidate', width: 22 },
    { header: 'Field Modified', key: 'field', width: 20 },
    { header: 'Old Value', key: 'oldValue', width: 18 },
    { header: 'New Value', key: 'newValue', width: 18 },
    { header: 'Mandatory Remark', key: 'remark', width: 35 },
    { header: 'Modified By', key: 'user', width: 20 },
    { header: 'Timestamp', key: 'timestamp', width: 22 },
  ];

  data.auditEntries.forEach((entry) => {
    auditSheet.addRow({
      candidate: entry.candidateName,
      field: entry.field,
      oldValue: entry.oldValue,
      newValue: entry.newValue,
      remark: entry.remark,
      user: `${entry.userName} (${entry.roleAtTime})`,
      timestamp: entry.createdAt,
    });
  });

  const buffer = await workbook.xlsx.writeBuffer();
  return new Uint8Array(buffer);
}

/**
 * Generates a clean PDF monthly report using pdf-lib.
 */
export async function generateMonthlyPdfReport(data: MonthlyReportData): Promise<Uint8Array> {
  const pdfDoc = await PDFDocument.create();
  const timesRoman = await pdfDoc.embedFont(StandardFonts.Helvetica);
  const boldFont = await pdfDoc.embedFont(StandardFonts.HelveticaBold);

  const page = pdfDoc.addPage([600, 800]);
  const { height } = page.getSize();

  // Header Title
  page.drawText('Candidate Compliance & Payments Report', {
    x: 40,
    y: height - 50,
    size: 18,
    font: boldFont,
    color: rgb(0.04, 0.06, 0.1),
  });

  page.drawText(`Period: ${data.month} ${data.year} | Generated by Admin`, {
    x: 40,
    y: height - 72,
    size: 11,
    font: timesRoman,
    color: rgb(0.3, 0.35, 0.4),
  });

  // Divider line
  page.drawLine({
    start: { x: 40, y: height - 85 },
    end: { x: 560, y: height - 85 },
    thickness: 1,
    color: rgb(0.8, 0.85, 0.9),
  });

  // KPI Summary box
  let totalPayable = 0;
  let totalCollected = 0;
  let overdueCount = 0;

  data.candidates.forEach((c) => {
    const insts = c.paymentPlan?.installments || [];
    totalPayable += c.paymentPlan?.totalPayable || 0;
    totalCollected += insts
      .filter((i) => i.status === 'PAID')
      .reduce((sum, i) => sum + i.amount, 0);
    overdueCount += insts.filter((i) => i.status === 'OVERDUE').length;
  });

  page.drawText('Executive Collections Summary:', {
    x: 40,
    y: height - 110,
    size: 13,
    font: boldFont,
    color: rgb(0.1, 0.15, 0.2),
  });

  page.drawText(
    `Total Active Candidates: ${data.candidates.length}    Total Payable: $${totalPayable.toLocaleString()}    Total Collected: $${totalCollected.toLocaleString()}    Overdue: ${overdueCount} Slots`,
    {
      x: 40,
      y: height - 130,
      size: 10,
      font: timesRoman,
      color: rgb(0.15, 0.2, 0.25),
    }
  );

  // Table header
  let yPosition = height - 165;
  page.drawRectangle({
    x: 40,
    y: yPosition - 5,
    width: 520,
    height: 22,
    color: rgb(0.92, 0.95, 0.98),
  });

  page.drawText('Candidate', { x: 45, y: yPosition, size: 9, font: boldFont });
  page.drawText('End Client', { x: 180, y: yPosition, size: 9, font: boldFont });
  page.drawText('Payable', { x: 300, y: yPosition, size: 9, font: boldFont });
  page.drawText('Collected', { x: 360, y: yPosition, size: 9, font: boldFont });
  page.drawText('BGC', { x: 430, y: yPosition, size: 9, font: boldFont });
  page.drawText('Status', { x: 495, y: yPosition, size: 9, font: boldFont });

  yPosition -= 22;

  data.candidates.slice(0, 20).forEach((cand) => {
    const insts = cand.paymentPlan?.installments || [];
    const collected = insts
      .filter((i) => i.status === 'PAID')
      .reduce((sum, i) => sum + i.amount, 0);
    const payable = cand.paymentPlan?.totalPayable || cand.upfrontAmount;

    page.drawText(cand.candidateName.slice(0, 22), { x: 45, y: yPosition, size: 8, font: timesRoman });
    page.drawText(cand.endClient.slice(0, 20), { x: 180, y: yPosition, size: 8, font: timesRoman });
    page.drawText(`$${payable.toLocaleString()}`, { x: 300, y: yPosition, size: 8, font: timesRoman });
    page.drawText(`$${collected.toLocaleString()}`, { x: 360, y: yPosition, size: 8, font: timesRoman });
    page.drawText(cand.bgcOfferStatus, { x: 430, y: yPosition, size: 8, font: timesRoman });
    page.drawText(cand.status, { x: 495, y: yPosition, size: 8, font: timesRoman });

    yPosition -= 18;
  });

  return await pdfDoc.save();
}

